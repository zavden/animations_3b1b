class _SynthGPT:
    """Returns (tokens, probs) of the next token, like gpt2_predict_next_token / gpt3_predict_next_token."""
    EOS = 50256

    def __init__(self):
        import tiktoken  # noqa: PLC0415
        self.enc = enc = tiktoken.get_encoding("gpt2")
        self.V = V = enc.n_vocab
        data_dir = Path(get_directories()["data"], "2024/transformers/data")
        data = _json.loads(Path(data_dir, "synthetic_gpt_data.json").read_text(encoding="utf-8"))
        self.first_steps = {k: [(t, p) for t, p in v] for k, v in data["first_steps"].items()}

        # Which tokens may appear (no line breaks, loose spaces or loose UTF-8 bytes)
        self.valid = valid = np.zeros(V, dtype=bool)
        for i in range(V - 1):
            try:
                s = enc.decode_single_token_bytes(i).decode("utf-8")
            except UnicodeDecodeError:
                continue
            valid[i] = bool(s.strip()) and s.isprintable()

        # Class of each token (leading space, lowercase / uppercase / digit / sign): the substitutions of a
        # script word are of the same class
        self.kind = np.zeros(V, dtype=int)
        for i in np.flatnonzero(valid):
            s = enc.decode_single_token_bytes(int(i)).decode("utf-8")
            body = s.lstrip(" ")
            kind = 1 if body[:1].islower() else 2 if body[:1].isupper() else 3 if body[:1].isdigit() else 4
            self.kind[i] = kind + (10 if s.startswith(" ") else 0)

        # Scripts: full texts (the last group ends with <|endoftext|>)
        scripts = [enc.encode(s, disallowed_special=()) for s in data["scripts"]]
        answers = [
            enc.encode(a_prompt + "\n\n" + "AI Assistant:" + ans, disallowed_special=())
            for a_prompt in ["User: How and when was the internet invented?"]
            for ans in data["chat_answers"]
        ]
        self.scripts = scripts + answers
        self.eos_scripts = set(range(len(scripts), len(scripts) + len(answers)))
        # A chatbot's answers are almost always kept intact (no random substitutions)
        self.clean = {i for i, s in enumerate(data["scripts"] + data["chat_answers"]) if i >= len(scripts) or "AI Assistant:" in s}

        # Background corpus: A Tale of Two Cities + placeholders, without line breaks
        def read(name, limit=None):
            path = Path(data_dir, name)
            text = path.read_text(encoding="utf-8", errors="ignore") if path.exists() else ""
            if name.startswith("tale") and "It was the best of times" in text:
                text = text[text.index("It was the best of times"):]
            return " ".join(text[:limit].split())
        modern_ids = enc.encode(read("facts.txt") + " " + read("pile_of_text.txt"), disallowed_special=())
        bg_ids = enc.encode(read("tale_of_two_cities.txt", 150_000), disallowed_special=()) + modern_ids
        # "Modern" vocabulary: what appears in the scripts and in the placeholder texts (not in the novel)
        self.modern = np.zeros(V, dtype=bool)
        for seq in self.scripts + [modern_ids]:
            self.modern[seq] = True

        # N-gram tables (contexts of 1 to 3 tokens); the scripts weigh twice as much as the background
        self.tables = {1: {}, 2: {}, 3: {}}
        uni = np.zeros(V)
        for seq, weight in [(bg_ids, 1)] + [(s, 2) for s in self.scripts]:
            for i, tok in enumerate(seq):
                uni[tok] += weight
                for k in (1, 2, 3):
                    if i >= k:
                        entry = self.tables[k].setdefault(tuple(seq[i - k:i]), {})
                        entry[tok] = entry.get(tok, 0) + weight
        rank_prior = 1.0 / (np.arange(V) + 30.0) ** 1.05
        base = 0.5 * rank_prior / rank_prior.sum() + 0.5 * (uni + 1e-2) / (uni + 1e-2).sum()
        base[~valid] = 0
        self.base = base / base.sum()

    def _hash01(self, *key):
        return _zlib.crc32(":".join(map(str, key)).encode()) / 2**32

    def next_probs(self, ids):
        p = self.base.copy()
        for k in (1, 2, 3):
            if len(ids) < k:
                break
            table = self.tables[k].get(tuple(ids[-k:]))
            if not table:
                break
            q = np.zeros(self.V)
            q[list(table.keys())] = list(table.values())
            n, t = q.sum(), len(table)
            p = (q + t * p) / (n + t)
        p[~self.valid] = 0

        # "Author" predictions for the exact prefix
        text = self.enc.decode(ids)
        over = []
        for tok, pr in self.first_steps.get(text, []):
            enc_tok = self.enc.encode(tok, disallowed_special=())
            if len(enc_tok) == 1:
                over.append((enc_tok[0], pr))
        if not over:
            over = self.script_guess(ids)
            if over:
                # The other options resemble the script word: same class, modern vocabulary
                main = max(over, key=lambda item: item[1])[0]
                p *= np.where(self.kind == self.kind[main], 1.0, 0.08) * np.where(self.modern, 1.0, 0.1)
        if over:
            idx = [i for i, _ in over]
            mass = sum(pr for _, pr in over)
            cap = 0.8 * min(pr for _, pr in over)
            p[idx] = 0
            p *= (1 - mass) / p.sum()
            for _ in range(4):  # the rest of the tokens do not exceed the author ones
                p = np.minimum(p, cap)
                p[idx] = 0
                p *= (1 - mass) / p.sum()
            for i, pr in over:
                p[i] = pr
        return p / p.sum()

    def script_guess(self, ids, window=5):
        """If the text follows (with small substitutions) one of the scripts, the word the script puts next is the most probable. The text is aligned with each script: what does not match is treated as a
        substitution, or as a jump of a few words if the token appears a little further ahead."""
        best_score, found = 2, {}
        for s_idx, script in enumerate(self.scripts):
            n_common = 0
            while n_common < min(len(ids), len(script)) and ids[n_common] == script[n_common]:
                n_common += 1
            if n_common < 3:
                continue
            ptr, score = n_common - 1, n_common
            for tok in ids[n_common:]:
                ahead = script[ptr + 1:ptr + 2 + window]
                if tok in ahead:
                    ptr += 1 + ahead.index(tok)
                    score += 1
                else:
                    ptr += 1
            if ptr + 1 < len(script):
                h = self._hash01(s_idx, ptr)  # some words are more uncertain than others
                nxt, weight = script[ptr + 1], (0.4 + 1.2 * h if h < 0.25 else 0.75 + 0.22 * (h - 0.25) / 0.75)
                if s_idx in self.clean:
                    weight = 0.97 + 0.02 * h
            elif ptr + 1 == len(script) and s_idx in self.eos_scripts:
                nxt, weight = self.EOS, 0.97
            else:
                continue
            if score > best_score:
                best_score, found = score, {}
            if score == best_score:
                found[nxt] = max(found.get(nxt, 0), weight)
        if not found:
            return []
        scale = min(1.0, 0.985 / sum(found.values()))
        return [(tok, w * scale) for tok, w in found.items()]

    def predict(self, text, n_shown):
        ids = self.enc.encode(text, disallowed_special=())
        p = self.next_probs(ids)
        top = np.argpartition(-p, n_shown)[:n_shown]
        top = top[np.argsort(-p[top])]
        return [self.enc.decode([int(i)]) for i in top], p[top]


